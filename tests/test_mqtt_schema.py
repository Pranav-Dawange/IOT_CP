# -----------------------------------------------------------------------------
# 1. Telemetry Schema & Ground-Truth Isolation Tests
# -----------------------------------------------------------------------------

def test_telemetry_payload_schema_valid():
    """Verify TelemetryPayload creates and serializes valid schema conforming to ML contract."""
    payload = TelemetryPayload(
        asset_id="asset_01",
        timestamp="2026-10-10T12:00:00Z",
        sequence_number=42,
        air_temperature=298.15,
        process_temperature=308.65,
        rotational_speed=1500.0,
        torque=40.5,
        tool_wear=12.0,
    )
    d = payload.to_dict()
    assert d["asset_id"] == "asset_01"
    assert d["sequence_number"] == 42
    assert d["air_temperature"] == 298.15
    assert d["process_temperature"] == 308.65
    assert d["rotational_speed"] == 1500.0
    assert d["torque"] == 40.5
    assert d["tool_wear"] == 12.0

    # Parse back from dict
    restored = TelemetryPayload.from_dict(d)
    assert restored == payload


def test_telemetry_prohibits_all_ground_truth_leakage():
    """
    CRITICAL SECURITY & METHODOLOGICAL TEST:
    Telemetry payload MUST NEVER contain Machine failure, failure modes, or raw dataset IDs.
    """
    for prohibited in PROHIBITED_LEAKAGE_COLUMNS:
        bad_dict = {
            "asset_id": "asset_01",
            "timestamp": "2026-10-10T12:00:00Z",
            "sequence_number": 1,
            "air_temperature": 298.15,
            "process_temperature": 308.65,
            "rotational_speed": 1500.0,
            "torque": 40.5,
            "tool_wear": 12.0,
            prohibited: 0,
        }
        with pytest.raises(ValueError, match=f"Prohibited column '{prohibited}' detected"):
            TelemetryPayload.from_dict(bad_dict)


def test_sensor_generator_emitted_readings_have_no_leakage():
    """Verify readings generated by SensorDataGenerator contain zero prohibited keys."""
    gen = SensorDataGenerator("asset_01", 0, 499)
    # Sample multiple readings across the slice
    for cursor in [0, 50, 100, 200, 350, 499]:
        reading = gen.generate_valid_reading(cursor, cursor + 1, "2026-10-10T12:00:00Z")
        reading_dict = reading.to_dict()
        for col in PROHIBITED_LEAKAGE_COLUMNS:
            assert col not in reading_dict, f"Prohibited column {col} leaked into reading at cursor {cursor}!"


