@pytest.mark.asyncio
async def test_mqtt_telemetry_topic_qos_retain():
    """Verify telemetry publication uses correct topic, QoS 0, and retain False."""
    transport = AsyncMQTTTransport(dry_run=True)
    await transport.connect()

    payload = {"asset_id": "asset_01", "sequence_number": 1}
    success = await transport.publish_telemetry("lineA", "asset_01", payload)
    assert success is True

    history = transport.get_published_history()
    assert len(history) == 1
    msg = history[0]
    assert msg["topic"] == "factory/lineA/asset_01/telemetry"
    assert msg["qos"] == 0
    assert msg["retain"] is False


