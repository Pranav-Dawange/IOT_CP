@pytest.mark.asyncio
async def test_transport_supports_bytes_and_str_without_json_dumps():
    """
    Verify transport can directly publish raw bytes (corrupted json) without error
    and without attempting to run json.dumps().
    """
    transport = AsyncMQTTTransport(dry_run=True)
    await transport.connect()

    raw_corrupted_bytes = b'{"broken": [INVALID_JSON'
    success = await transport.publish_telemetry("lineA", "asset_01", raw_corrupted_bytes)
    assert success is True

    history = transport.get_published_history()
    assert len(history) == 1
    assert history[0]["raw_payload"] == raw_corrupted_bytes


def test_status_payload_global_row_index_preservation():
    """Verify status payload retains global CSV row index."""
    status = StatusPayload(
        asset_id="asset_05",
        line="lineA",
        status="ONLINE",
        timestamp="2026-10-10T12:00:00Z",
        sequence_number=1,
        source_row_index=2000,
        reason="heartbeat",
    )
    d = status.to_dict()
    assert d["source_row_index"] == 2000
    assert d["reason"] == "heartbeat"
    assert d["status"] == "ONLINE"
