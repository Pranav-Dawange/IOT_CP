"""
Test Suite for MQTT Schema Conformance, Ground-Truth Isolation, and Topic Routing.

Covers:
1. Valid TelemetryPayload schema conformance (only 5 raw ML sensor features + metadata).
2. Strict ground-truth isolation: zero occurrences of prohibited failure labels or dataset IDs.
3. Strict topic hierarchy: factory/{line}/{asset_id}/{telemetry|status|alerts}.
4. QoS and retain enforcement:
   - Telemetry: QoS 0, Retain False
   - Status:    QoS 1, Retain True
   - Alerts:    QoS 1, Retain False
5. Malformed payload detection and schema rejection.
"""

